"""Module for converting integers to Roman numerals."""


def number_to_roman(number):
    """Converts an integer to a Roman numeral string."""
    number = int(number)
    if number <= 0:
        raise ValueError("Number must be a positive integer.")

    val_map = [
        (1000, "M"),
        (900, "CM"),
        (500, "D"),
        (400, "CD"),
        (100, "C"),
        (90, "XC"),
        (50, "L"),
        (40, "XL"),
        (10, "X"),
        (9, "IX"),
        (5, "V"),
        (4, "IV"),
        (1, "I"),
    ]

    roman = ""
    for value, numeral in val_map:
        while number >= value:
            roman += numeral
            number -= value

    return roman
